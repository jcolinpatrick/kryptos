def main():
    parser = argparse.ArgumentParser(
        description="Exhaustive Sculpture Reading Path Search v1"
    )
    parser.add_argument('--family', type=int, default=0,
                        help='Run single family (1-6) or 0=all')
    parser.add_argument('--threshold', type=int, default=12,
                        help='Minimum score to report (default: 12)')
    parser.add_argument('--workers', type=int, default=0,
                        help='Number of multiprocessing workers (0=auto, 1=serial)')
    parser.add_argument('--batch-size', type=int, default=1000,
                        help='Batch size for multiprocessing dispatch')
    args = parser.parse_args()

    global THRESHOLD
    THRESHOLD = args.threshold

    n_workers = args.workers if args.workers > 0 else cpu_count()

    families = {
        1: ("Tableau 26x26", gen_family_1),
        2: ("Master Grid 28x31", gen_family_2),
        3: ("Keyword-Parameterized", gen_family_3),
        4: ("Coordinate-Parameterized", gen_family_4),
        5: ("Compound Paths", gen_family_5),
        6: ("Morse & Physical Features", gen_family_6),
    }

    if args.family:
        if args.family not in families:
            print(f"Unknown family {args.family}. Valid: 1-6", flush=True)
            sys.exit(1)
        families = {args.family: families[args.family]}

    print("=" * 78, flush=True)
    print("SCULPTURE READING PATH SEARCH v1", flush=True)
    print(f"Threshold: {THRESHOLD}/24  Families: {sorted(families.keys())}  "
          f"Workers: {n_workers}", flush=True)
    print(f"Surfaces: TABLEAU 26x26={len(TABLEAU_FLAT)}ch, "
          f"MASTER_CT 28x31={len(MASTER_CT_FLAT)}ch, "
          f"MASTER_PT 28x31={len(MASTER_PT_FLAT)}ch", flush=True)
    print("=" * 78, flush=True)

    all_hits = []
    total_paths = 0
    total_tests = 0
    t0 = time.time()

    use_mp = n_workers > 1

    for fam_num, (fam_name, gen_func) in sorted(families.items()):
        print(f"\n--- Family {fam_num}: {fam_name} ---", flush=True)
        fam_paths = 0
        fam_tests = 0
        fam_t0 = time.time()

        if use_mp:
            # ── Multiprocessing mode ──────────────────────────────────────
            batch = []
            pool = Pool(processes=n_workers)
            pending_results = []

            for key_chars, desc in gen_func():
                if not key_chars or not key_chars.isalpha():
                    continue
                batch.append((key_chars, desc, fam_num))
                fam_paths += 1

                if len(batch) >= args.batch_size:
                    pending_results.append(pool.apply_async(_score_batch, (batch,)))
                    # Count approximate tests
                    for kc, _, _ in batch:
                        fam_tests += max(1, len(kc) - 96) if len(kc) >= 97 else 1
                    batch = []

                    if fam_paths % 10000 == 0:
                        elapsed = time.time() - fam_t0
                        print(f"  {fam_paths:>8,} paths dispatched | "
                              f"{len(pending_results)} batches | "
                              f"{elapsed:.1f}s", flush=True)

            # Flush remaining batch
            if batch:
                pending_results.append(pool.apply_async(_score_batch, (batch,)))
                for kc, _, _ in batch:
                    fam_tests += max(1, len(kc) - 96) if len(kc) >= 97 else 1

            pool.close()

            # Collect results
            print(f"  Collecting {len(pending_results)} batches...", flush=True)
            for res in pending_results:
                batch_hits = res.get()
                for h in batch_hits:
                    all_hits.append(h)
                    if h['score'] >= 18:
                        print(f'  *** SIGNAL: {h["score"]}/24 {h["variant"]} '
                              f'{h["desc"]} offset={h.get("offset", "?")}',
                              flush=True)

            pool.join()

        else:
            # ── Serial mode ───────────────────────────────────────────────
            for key_chars, desc in gen_func():
                if not key_chars or not key_chars.isalpha():
                    continue

                tests = test_path(key_chars, desc, fam_num, all_hits)
                fam_tests += tests
                fam_paths += 1

                if fam_paths % 10000 == 0:
                    elapsed = time.time() - fam_t0
                    print(f"  {fam_paths:>8,} paths | {fam_tests:>10,} tests | "
                          f"{len(all_hits)} hits >= {THRESHOLD} | "
                          f"{elapsed:.1f}s", flush=True)

        fam_elapsed = time.time() - fam_t0
        print(f"  DONE: {fam_paths:,} paths, {fam_tests:,} tests, "
              f"{len(all_hits)} total hits >= {THRESHOLD}, "
              f"{fam_elapsed:.1f}s", flush=True)

        total_paths += fam_paths
        total_tests += fam_tests

    elapsed = time.time() - t0

    # ── Summary ──────────────────────────────────────────────────────────────
    print("\n" + "=" * 78, flush=True)
    print(f"COMPLETE: {total_paths:,} paths, {total_tests:,} tests, "
          f"{elapsed:.1f}s", flush=True)
    print(f"Hits >= {THRESHOLD}/24: {len(all_hits)}", flush=True)

    all_hits.sort(key=lambda x: -x['score'])

    # ── Hit analysis ─────────────────────────────────────────────────────────
    if all_hits:
        print(f"\nTop results:", flush=True)
        for h in all_hits[:20]:
            offset_str = f" off={h.get('offset', '?')}" if 'offset' in h else ""
            print(f"  {h['score']:>2}/24 {h['variant']:<10} "
                  f"F{h['family']} {h['desc'][:55]}{offset_str}", flush=True)

        # Detailed analysis for scores >= 12
        for h in all_hits:
            if h['score'] < 12:
                break
            key_preview = h.get('key_preview', '')
            desc = h['desc']
            variant = h['variant']
            score = h['score']
            offset = h.get('offset', 0)

            # Reconstruct key for decryption
            # For long-key hits, we need the 97-char window; key_preview is only 30 chars
            # So we regenerate if possible, or just use preview info
            if score >= 18:
                print(f"\n  {'*' * 60}", flush=True)
                print(f"  *** SIGNAL *** {score}/24 {variant}", flush=True)
                print(f"  Path: {desc}", flush=True)
                print(f"  Key preview: {key_preview}", flush=True)
                print(f"  {'*' * 60}", flush=True)
            elif score >= 12:
                print(f"\n  -- Hit {score}/24 {variant} | {desc} | key: {key_preview}",
                      flush=True)
    else:
        print(f"\nNo paths scored >= {THRESHOLD}/24.", flush=True)

    # ── Save results ─────────────────────────────────────────────────────────
    output_dir = os.path.join(_ROOT, 'results')
    os.makedirs(output_dir, exist_ok=True)
    output = os.path.join(output_dir, 'f_sculpture_path_search_v1.json')

    with open(output, 'w') as f:
        json.dump({
            'total_paths': total_paths,
            'total_tests': total_tests,
            'threshold': THRESHOLD,
            'workers': n_workers,
            'elapsed_seconds': round(elapsed, 1),
            'hit_count': len(all_hits),
            'hits': all_hits[:200],
        }, f, indent=2)
    print(f"\nResults saved: {output}", flush=True)


