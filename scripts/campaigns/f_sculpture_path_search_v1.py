def score_key(key_chars):
    """Test key_chars as cipher key under 4 variants.

    For keys shorter than 97, cycle them.
    Returns list of (score, variant_name).
    """
    if not key_chars:
        return []

    key_upper = key_chars.upper()
    key_len = len(key_upper)
    hits = []

    for variant_name, decrypt_func in [
        ('beau_az', lambda ct_c, k_c: (ALPH_IDX[k_c] - ALPH_IDX[ct_c]) % 26),
        ('vig_az', lambda ct_c, k_c: (ALPH_IDX[ct_c] - ALPH_IDX[k_c]) % 26),
        ('beau_ka', lambda ct_c, k_c: (KA_IDX[k_c] - KA_IDX[ct_c]) % 26),
        ('vig_ka', lambda ct_c, k_c: (KA_IDX[ct_c] - KA_IDX[k_c]) % 26),
    ]:
        score = 0
        for pos in CRIB_POS:
            key_idx = pos % key_len
            k_c = key_upper[key_idx]
            if k_c not in ALPH_IDX:
                continue
            pt_val = decrypt_func(CT[pos], k_c)
            if variant_name.endswith('_ka'):
                pt_char = KA[pt_val]
            else:
                pt_char = ALPH[pt_val]
            if pt_char == CRIB_DICT[pos]:
                score += 1
        if score >= THRESHOLD:
            hits.append((score, variant_name))
    return hits


def test_path(key_chars, desc, family, hits_list):
    """Score a key at all valid offsets (for long keys) or cycled (for short).

    Appends any hits >= THRESHOLD to hits_list. Returns number of tests run.
    """
    if not key_chars:
        return 0

    tests = 0
    klen = len(key_chars)

    if klen >= 97:
        # Sliding window: test every 97-char window
        for offset in range(klen - 96):
            window = key_chars[offset:offset + 97]
            results = score_key(window)
            tests += 1
            for score, variant in results:
                hits_list.append({
                    'score': score, 'variant': variant,
                    'family': family, 'desc': desc,
                    'offset': offset, 'key_preview': window[:30],
                })
                if score >= 18:
                    print(f'  *** SIGNAL: {score}/24 {variant} {desc} offset={offset}',
                          flush=True)
    else:
        # Short key: cycle it
        results = score_key(key_chars)
        tests += 1
        for score, variant in results:
            hits_list.append({
                'score': score, 'variant': variant,
                'family': family, 'desc': desc,
                'offset': 0, 'key_preview': key_chars[:30],
            })
            if score >= 18:
                print(f'  *** SIGNAL: {score}/24 {variant} {desc}', flush=True)

    return tests


