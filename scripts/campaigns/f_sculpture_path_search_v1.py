def _score_batch(batch):
    """Score a batch of (key_chars, description, family_num) tuples.

    Returns list of hit dicts for scores >= THRESHOLD.
    """
    hits = []
    for key_chars, desc, fam_num in batch:
        if not key_chars or not key_chars.isalpha():
            continue
        klen = len(key_chars)
        if klen >= 97:
            for offset in range(klen - 96):
                window = key_chars[offset:offset + 97]
                results = score_key(window)
                for score, variant in results:
                    hits.append({
                        'score': score, 'variant': variant,
                        'family': fam_num, 'desc': desc,
                        'offset': offset, 'key_preview': window[:30],
                    })
        else:
            results = score_key(key_chars)
            for score, variant in results:
                hits.append({
                    'score': score, 'variant': variant,
                    'family': fam_num, 'desc': desc,
                    'offset': 0, 'key_preview': key_chars[:30],
                })
    return hits


def _decrypt_full(key_chars, variant):
    """Decrypt CT with key_chars under the given variant. Returns 97-char PT."""
    key_upper = key_chars.upper()
    key_len = len(key_upper)
    pt = []
    for i in range(len(CT)):
        k_c = key_upper[i % key_len]
        ct_c = CT[i]
        if variant == 'beau_az':
            val = (ALPH_IDX[k_c] - ALPH_IDX[ct_c]) % 26
            pt.append(ALPH[val])
        elif variant == 'vig_az':
            val = (ALPH_IDX[ct_c] - ALPH_IDX[k_c]) % 26
            pt.append(ALPH[val])
        elif variant == 'beau_ka':
            val = (KA_IDX[k_c] - KA_IDX[ct_c]) % 26
            pt.append(KA[val])
        elif variant == 'vig_ka':
            val = (KA_IDX[ct_c] - KA_IDX[k_c]) % 26
            pt.append(KA[val])
    return ''.join(pt)


