def _read_grid_rows(grid, nrows, ncols, mode='lr', start_row=0):
    """Read a grid row-by-row with specified mode.

    mode: 'lr' = left-to-right, 'rl' = right-to-left, 'boustro' = alternating
    start_row: which row to start from (wraps around)
    """
    chars = []
    for i in range(nrows):
        r = (start_row + i) % nrows
        row = grid[r]
        row_str = row if isinstance(row, str) else ''.join(row)
        if mode == 'lr':
            chars.append(row_str)
        elif mode == 'rl':
            chars.append(row_str[::-1])
        elif mode == 'boustro':
            if i % 2 == 0:
                chars.append(row_str)
            else:
                chars.append(row_str[::-1])
    return ''.join(chars)


def _read_grid_cols(grid, nrows, ncols, mode='tb', start_col=0):
    """Read a grid column-by-column.

    mode: 'tb' = top-to-bottom, 'bt' = bottom-to-top, 'boustro' = alternating
    """
    chars = []
    for j in range(ncols):
        c = (start_col + j) % ncols
        col_chars = []
        for r in range(nrows):
            row = grid[r]
            row_str = row if isinstance(row, str) else ''.join(row)
            if c < len(row_str):
                col_chars.append(row_str[c])
        col_str = ''.join(col_chars)
        if mode == 'tb':
            chars.append(col_str)
        elif mode == 'bt':
            chars.append(col_str[::-1])
        elif mode == 'boustro':
            if j % 2 == 0:
                chars.append(col_str)
            else:
                chars.append(col_str[::-1])
    return ''.join(chars)


def _read_diagonal(flat, nrows, ncols, dr, dc, start_r, start_c):
    """Read a diagonal path through a grid (with wrapping).

    Returns nrows*ncols chars by stepping (dr, dc) with mod wrapping.
    """
    total = nrows * ncols
    chars = []
    r, c = start_r, start_c
    visited = set()
    for _ in range(total):
        idx = r * ncols + c
        if idx in visited:
            break
        visited.add(idx)
        chars.append(flat[idx])
        r = (r + dr) % nrows
        c = (c + dc) % ncols
    return ''.join(chars)


def _read_spiral(grid, nrows, ncols, clockwise=True, start_corner=0):
    """Read a grid in spiral order.

    start_corner: 0=top-left, 1=top-right, 2=bottom-right, 3=bottom-left
    """
    # Build flat matrix for indexing
    mat = []
    for r in range(nrows):
        row = grid[r]
        row_str = row if isinstance(row, str) else ''.join(row)
        mat.append(list(row_str))

    # Transform so top-left is always the start corner
    # Then read spiral, then the result is the same regardless
    if start_corner == 1:
        # Flip horizontally
        mat = [row[::-1] for row in mat]
    elif start_corner == 2:
        # Flip both
        mat = [row[::-1] for row in mat[::-1]]
    elif start_corner == 3:
        # Flip vertically
        mat = mat[::-1]

    if not clockwise:
        # Transpose for counter-clockwise
        new_mat = []
        for c in range(len(mat[0]) if mat else 0):
            new_mat.append([mat[r][c] for r in range(len(mat))])
        mat = new_mat
        nrows, ncols = ncols, nrows

    # Standard CW spiral from top-left
    chars = []
    top, bottom, left, right = 0, len(mat) - 1, 0, (len(mat[0]) - 1 if mat else 0)
    while top <= bottom and left <= right:
        for c in range(left, right + 1):
            chars.append(mat[top][c])
        top += 1
        for r in range(top, bottom + 1):
            chars.append(mat[r][right])
        right -= 1
        if top <= bottom:
            for c in range(right, left - 1, -1):
                chars.append(mat[bottom][c])
            bottom -= 1
        if left <= right:
            for r in range(bottom, top - 1, -1):
                chars.append(mat[r][left])
            left += 1

    return ''.join(chars)


def gen_family_1():
    """Yield (key_chars, description) for all Family 1 paths on the 26x26 tableau."""
    nrows, ncols = 26, 26

    # 1. Row reads: 3 modes × 26 start rows = 78
    for mode in ('lr', 'rl', 'boustro'):
        for sr in range(nrows):
            key = _read_grid_rows(TABLEAU, nrows, ncols, mode, sr)
            yield key, f"tab_rows_{mode}_start{sr}"

    # 2. Column reads: 3 modes × 26 start cols = 78
    for mode in ('tb', 'bt', 'boustro'):
        for sc in range(ncols):
            key = _read_grid_cols(TABLEAU, nrows, ncols, mode, sc)
            yield key, f"tab_cols_{mode}_start{sc}"

    # 3. Diagonals: 4 directions × starting edges
    diag_dirs = [
        (1, 1, "SE"),    # ↘
        (1, -1, "SW"),   # ↙
        (-1, 1, "NE"),   # ↗
        (-1, -1, "NW"),  # ↖
    ]
    for dr, dc, name in diag_dirs:
        # Start from top edge (row 0, all cols) and left edge (all rows, col 0)
        starts = set()
        for c in range(ncols):
            starts.add((0, c))
        for r in range(nrows):
            starts.add((r, 0))
        for sr, sc in sorted(starts):
            key = _read_diagonal(TABLEAU_FLAT, nrows, ncols, dr, dc, sr, sc)
            if len(key) >= 2:
                yield key, f"tab_diag_{name}_from({sr},{sc})"

    # 4. Spirals: CW and CCW from 4 corners = 8
    for cw in (True, False):
        for corner in range(4):
            key = _read_spiral(TABLEAU, nrows, ncols, cw, corner)
            cw_str = "CW" if cw else "CCW"
            yield key, f"tab_spiral_{cw_str}_corner{corner}"

    # 5. Skip-N on flat tableau: N=2..13, offsets 0..N-1, row-major + col-major
    # Row-major flat
    for skip_n in range(2, 14):
        for offset in range(skip_n):
            key = TABLEAU_FLAT[offset::skip_n]
            if key:
                yield key, f"tab_skip{skip_n}_rowmaj_off{offset}"

    # Column-major flat
    col_major = _read_grid_cols(TABLEAU, nrows, ncols, 'tb', 0)
    for skip_n in range(2, 14):
        for offset in range(skip_n):
            key = col_major[offset::skip_n]
            if key:
                yield key, f"tab_skip{skip_n}_colmaj_off{offset}"


