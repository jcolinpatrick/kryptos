    fp = sum(1 for p in palette_positions if p in predicted_nulls_set and not labels[p])
    fn = sum(1 for p in palette_positions if p not in predicted_nulls_set and labels[p])
    tn = sum(1 for p in palette_positions if p not in predicted_nulls_set and not labels[p])
    return (tp + tn, tp, fp, fn, tn)

