                for S in range(M):
                    pred_null = set(p for p in palette_positions
                                  if op_fn(features[p][f1_name], features[p][f2_name]) % M == S)
                    acc, tp, fp, fn, tn = score_rule(pred_null)
                    # Check both: null if in S, and null if NOT in S
