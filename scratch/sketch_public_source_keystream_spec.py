"""Sketch: K4 keystream from a 1990-era public source text (M3 SKIP variant).

Category A. DSL-translatable via the `key_tape` kind.

Reference: Cicada 3301 Liber Primus uses a fixed source text whose letter
ordinals form the additive keystream, with selective characters not
consuming tape positions. The structural analogue for K4 is:

  Model:   M3 (finite tape, SKIP null rule)
  Cipher:  Beaufort A=0 (matches K1/K2/K3 pedagogical arc)
  Tape:    integer ordinals of a candidate 1990-era text, sliced at offset
  Skip:    keystream advances only at positions not declared null

The 24 crib-position keystream values (Beaufort A=0) are
JLJODEGKUKKKLOCGGBGOKTRU. For a candidate (text, offset, null_mask) to
survive, the tape values at the *unskipped* crib positions must reproduce
those 24 values.

The 60K Gutenberg sweep (eliminated) was M0/M1: no nulls, tape consumes
every position. M3 produces a genuinely different keystream from the same
text + offset, so this is not a re-test of an eliminated universe.
"""

from __future__ import annotations

# DECISION POINT 1 — source text shortlist. (RESOLVED 2026-05-11)
#
# Selected per user decision: KUBARK + Carter + NSA Cryptanalytics.
# All three are AAA-attested or AAA-context (intelligence tradecraft and
# the Egyptology reference Sanborn cited). All pre-1990 and outside the
# standard Gutenberg sweep that already eliminated generic running-key.
#
# Texts are pre-processed to alpha-only ASCII and stored under
# scratch/source_texts/. Loaded at spec-build time rather than inlined
